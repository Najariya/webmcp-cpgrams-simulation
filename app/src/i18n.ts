/**
 * UI locale table (EN/HI). Tool names, registration IDs and JSON payloads stay
 * English by design (agent contracts); everything the citizen reads is here.
 * The choice persists under "advocate-lang-v1".
 */
export type Lang = "en" | "hi";

const LANG_KEY = "advocate-lang-v1";

export function loadLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === "hi" ? "hi" : "en";
  } catch {
    return "en";
  }
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* storage unavailable — stays session-only */
  }
}

